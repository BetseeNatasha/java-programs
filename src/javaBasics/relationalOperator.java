package javaBasics;

public class relationalOperator {

	public static void main(String[] args) {
      boolean result;
      
      result=(5==5);
      System.out.println(result);
      
      result=(5<=5);
      System.out.println(result);
      
      result=(5<5);
      System.out.println(result);
      
      result=(10>=5);
      System.out.println(result);
      
      result=(10>5);
      System.out.println(result);
      
      result=(10!=10);
      System.out.println(result);
	}

}
